type JsonSchema = {
  type?: string | string[];
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema;
  enum?: unknown[];
  const?: unknown;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  maxLength?: number;
  minimum?: number;
  exclusiveMinimum?: number;
  additionalProperties?: unknown;
};

/** Renders a JSON Schema as a compact TypeScript-style type. */
export function renderType(schema: JsonSchema, indent = ''): string {
  const next = `${indent}  `;
  const union = schema.anyOf ?? schema.oneOf;
  if (union) {
    const parts = union.map((s) => renderType(s, indent));
    return parts.some((p) => p.includes('\n')) ? parts.join(`\n${indent}| `) : parts.join(' | ');
  }
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');

  const types = Array.isArray(schema.type) ? schema.type : [schema.type];
  const rendered = types.map((type) => {
    switch (type) {
      case 'object': {
        const props = Object.entries(schema.properties ?? {});
        if (props.length === 0) return '{}';
        const required = new Set(schema.required ?? []);
        const lines = props.map(([key, value]) => {
          const notes = [];
          if (value.maxLength !== undefined) notes.push(`max ${value.maxLength} chars`);
          const comment = notes.length ? ` // ${notes.join(', ')}` : '';
          return `${next}${key}${required.has(key) ? '' : '?'}: ${renderType(value, next)};${comment}`;
        });
        return `{\n${lines.join('\n')}\n${indent}}`;
      }
      case 'array': {
        const item = renderType(schema.items ?? {}, indent);
        return /[|\n]/.test(item) && !item.startsWith('{') ? `Array<${item}>` : `${item}[]`;
      }
      case 'integer':
        return 'number';
      case undefined:
        return 'unknown';
      default:
        return type;
    }
  });
  return rendered.join(' | ');
}

function block(schema: unknown): string {
  const json = z.toJSONSchema(schema as z.ZodType, {
    io: 'input',
    unrepresentable: 'any',
  }) as JsonSchema;
  return '```ts\n' + renderType(json) + '\n```';
}

interface RouteSchema {
  summary?: string;
  params?: unknown;
  body?: unknown;
  response?: Record<string, unknown>;
}

/** Builds docs/api.md from the schemas actually registered on the routes. */
export async function generateApiDocs(): Promise<string> {
  const routes: RouteOptions[] = [];
  const app = await buildApp({ ...testApp(), onRoute: (r) => routes.push(r) });
  await app.close();

  const sections = routes
    .filter((r) => r.url.startsWith('/api/') && r.method !== 'HEAD')
    .map((route) => {
      const schema = (route.schema ?? {}) as RouteSchema;
      const out = [`## \`${String(route.method)} ${route.url}\``, ''];
      if (schema.summary) out.push(schema.summary, '');
      if (schema.params) out.push('**Path params**', '', block(schema.params), '');
      if (schema.body) out.push('**Request body**', '', block(schema.body), '');
      for (const [status, response] of Object.entries(schema.response ?? {})) {
        out.push(`**${status} response**`, '', block(response), '');
      }
      return out.join('\n');
    });

  return [
    '# API reference',
    '',
    '<!-- Generated by `npm run docs:api` from the Zod schemas registered on each route. Do not edit by hand. -->',
    '',
    'All endpoints are JSON except the two Google sign-in redirects. Visitors start anonymous: the first request gets a signed, HTTP-only `theshire_learner` cookie. Signing in with Google adds a `theshire_session` cookie; progress then belongs to the account, and anything done anonymously in that browser is merged in. Every response carries an `X-Request-Id` header (an incoming one is kept).',
    '',
    'Errors share one shape:',
    '',
    '```ts\n{ error: { code: string; message: string } }\n```',
    '',
    '| Code | Meaning |',
    '| ---- | ------- |',
    ...Object.entries(ERROR_CODES).map(([code, meaning]) => `| \`${code}\` | ${meaning} |`),
    '',
    ...sections,
  ].join('\n');
}
